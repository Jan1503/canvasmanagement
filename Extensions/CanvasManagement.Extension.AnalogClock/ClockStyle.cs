namespace CanvasManagement.Extension.AnalogClock;

/// <summary>
///     Available analog clock styles
/// </summary>
public enum ClockStyle
{
    /// <summary>
    ///     Traditional analog clock with numbers and tick marks
    /// </summary>
    Classic,

    /// <summary>
    ///     Minimalist design with only essential elements
    /// </summary>
    Minimalist,

    /// <summary>
    ///     Classic clock with Roman numeral numbers
    /// </summary>
    Roman,

    /// <summary>
    ///     Modern design with gradient and dots
    /// </summary>
    Modern,

    /// <summary>
    ///     Clock that runs counter-clockwise (backwards)
    /// </summary>
    CounterClockwise,

    /// <summary>
    ///     Swiss railway station clock style
    /// </summary>
    Railway,

    /// <summary>
    ///     Transparent face showing only structure
    /// </summary>
    Skeleton,

    /// <summary>
    ///     Vintage retro-style clock
    /// </summary>
    Retro
}